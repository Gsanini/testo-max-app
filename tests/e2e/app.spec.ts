  await page.getByRole('button',{name:'Marcar como concluída',exact:true}).click()
  await expect(page.locator('.level-pill')).toContainText('10 XP')
  await expect.poll(async()=> (await workspace(page)).activities.find((activity:{journeyDay:number;role:string})=>activity.journeyDay===1&&activity.role==='habito').done).toBe(true)
