import { test, expect } from '@playwright/test'
import { enter, workspace } from './helpers'

test('lista única permite concluir em qualquer ordem e atualiza os dois progressos', async ({ page }) => {
  await enter(page)
  const daily = page.getByRole('progressbar', { name: 'Progresso do dia', exact: true })
  const total = page.getByRole('progressbar', { name: 'Dias concluídos na jornada' })
  await expect(daily).toHaveAttribute('aria-valuenow', '0')
  await expect(total).toHaveAttribute('value', '0')
  await expect(page.locator('.period-section')).toHaveCount(0)
  await expect(page.locator('.daily-checklist .activity-row')).toHaveCount(7)
  await expect(page.locator('.daily-checklist .meal-time')).toHaveCount(3)
  await expect(page.locator('.daily-checklist .flexible-time')).toHaveCount(4)
  await expect(page.getByRole('button', { name: /Dia 2: bloqueado/ })).toBeDisabled()

  const names=await page.locator('.daily-checklist .step-content strong').allTextContents()
  for(const [step,index] of [4,0,6,2,3,1,5].entries()){
    await page.getByRole('button',{name:`Concluir ${names[index]}`,exact:true}).click()
    await expect(daily).toHaveAttribute('aria-valuenow',String(Math.round((step+1)/7*100)))
    await expect(total).toHaveAttribute('value',step===6?'1':'0')
  }
  await expect(page.getByRole('heading', { name: 'Tudo feito por hoje. Muito bem!' })).toBeVisible()
  await expect.poll(async()=> (await workspace(page)).activities.filter((activity:{journeyDay:number;done:boolean})=>activity.journeyDay===1&&activity.done).length).toBe(7)
  await page.reload()
  await expect(daily).toHaveAttribute('aria-valuenow', '100')
  await expect(total).toHaveAttribute('value', '1')
  await page.getByRole('button', { name: 'Desfazer Luz natural por 10 minutos', exact: true }).click()
  await expect(daily).toHaveAttribute('aria-valuenow', '86')
  await expect(total).toHaveAttribute('value', '0')
  await expect(page.locator('.focus-action h2')).toHaveText('Luz natural por 10 minutos')
})

test('todos os passos exibem horário e duração objetivos', async ({ page }) => {
  await enter(page)
  await page.getByRole('button', { name: 'Abrir detalhes de Luz natural por 10 minutos', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('07:00 · 10 minutos')
  await expect(page.getByLabel('Horário desta atividade')).toHaveCount(0)
  await page.getByRole('button', { name: 'Fechar', exact: true }).click()
  await expect(page.locator('.daily-checklist .step-content').filter({hasText:'Luz natural por 10 minutos'})).toContainText('Horário sugerido · 07:00')

  await page.clock.setFixedTime(new Date('2026-10-17T18:30:00Z'))
  await page.clock.runFor(1100)
  await expect(page.locator('.focus-action h2')).toContainText('Almoço:')
  await page.getByRole('button', { name: 'Ver passo a passo', exact: true }).click()
  await page.getByRole('button', { name: 'Marcar como concluída', exact: true }).click()
  await expect(page.locator('.focus-action h2')).toHaveText('Recuperação: mobilidade suave')

  await page.clock.setFixedTime(new Date('2026-10-18T01:30:00Z'))
  await page.clock.runFor(1100)
  await expect(page.locator('.focus-action h2')).toContainText('Jantar:')
})

test('registrar refeição na lista e desfazer em Alimentação mantém as telas sincronizadas',async({page})=>{
  await enter(page)
  await page.getByRole('button',{name:/^Concluir Café da manhã:/}).click()
  await expect(page.getByRole('progressbar',{name:'Progresso do dia'})).toHaveAttribute('aria-valuetext','1 de 7 passos concluídos')
  await expect.poll(async()=> (await workspace(page)).meals.find((meal:{date:string;slot:string})=>meal.date==='2026-10-17'&&meal.slot==='breakfast').done).toBe(true)
  await page.goto('/alimentacao')
  await expect(page.getByRole('button',{name:'Desfazer Café da manhã',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Desfazer Café da manhã',exact:true}).click()
  await expect.poll(async()=> (await workspace(page)).meals.find((meal:{date:string;slot:string})=>meal.date==='2026-10-17'&&meal.slot==='breakfast').done).toBe(false)
  await page.goto('/')
  await expect(page.getByRole('button',{name:/^Concluir Café da manhã:/})).toBeVisible()
  await expect(page.getByRole('progressbar',{name:'Progresso do dia'})).toHaveAttribute('aria-valuetext','0 de 7 passos concluídos')
})

test('conteúdo futuro fica oculto no link direto, no histórico e em outro capítulo', async ({ page }) => {
  await enter(page)
  const state = await workspace(page)
  const futureTitles = state.activities.filter((activity: { journeyDay: number }) => activity.journeyDay === 2).map((activity: { title: string }) => activity.title)
  await page.goto('/?dia=2')
  await expect(page.getByRole('heading', { name: 'Dia 2 bloqueado' })).toBeVisible()
  for (const title of futureTitles) await expect(page.getByText(title, { exact: true })).toHaveCount(0)
  await expect(page.getByRole('progressbar')).toHaveCount(0)
  await page.getByRole('link', { name: 'Voltar ao dia atual' }).click()
  await expect(page.locator('.daily-checklist .activity-row')).toHaveCount(7)
  await page.goto('/historico')
  await page.getByRole('button', { name: 'Semana', exact: true }).click()
  await expect(page.getByRole('button', { name: /domingo, 18 de outubro: bloqueado/ })).toBeDisabled()
  await page.goto('/jornada')
  await expect(page.getByRole('button', { name: /Dia 2: bloqueado/ })).toBeDisabled()
  await page.getByRole('button', { name: /CAPÍTULO 4 Consolidar/ }).click()
  await expect(page.getByRole('button', { name: /Dia 120: bloqueado/ })).toBeDisabled()
  await expect(page.getByRole('dialog')).toHaveCount(0)
})
