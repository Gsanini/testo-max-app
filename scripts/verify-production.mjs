import {chromium} from '@playwright/test'
import assert from 'node:assert/strict'
import {readFile,readdir,mkdir} from 'node:fs/promises'
const browser=await chromium.launch({headless:true,channel:process.env.PLAYWRIGHT_CHANNEL || undefined})
const context=await browser.newContext({viewport:{width:390,height:844}})
const page=await context.newPage()
try {
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto('http://127.0.0.1:4173/')
  await page.getByRole('heading',{name:'Bom ter você por aqui.'}).waitFor()
  await page.getByRole('button',{name:'Entrar na minha rotina'}).click()
  for(let step=0;step<14;step++) await page.getByRole('button',{name:'Continuar',exact:true}).click()
  await page.getByRole('button',{name:'Começar minha jornada'}).click()
  await page.getByRole('heading',{name:'Seu próximo passo começa aqui.'}).waitFor()
  await page.evaluate(async()=>{await navigator.serviceWorker.ready})
  await page.reload()
  const cached=await page.evaluate(async()=>{const keys=await caches.keys();const urls=[];for(const key of keys){for(const request of await (await caches.open(key)).keys())urls.push(request.url)}return urls})
  assert.ok(cached.length>10)
  assert.ok(cached.every(url=>new URL(url).origin==='http://127.0.0.1:4173'))
  assert.ok(cached.every(url=>!/(supabase|\/api\/|access_token)/.test(url)))
  const manifest=JSON.parse(await readFile('dist/manifest.webmanifest','utf8'))
  assert.equal(manifest.id,'/');assert.equal(manifest.display,'standalone');assert.ok(manifest.icons.some(i=>i.purpose==='maskable'))
  const scripts=await readdir('dist/assets')
  for(const file of scripts.filter(f=>f.endsWith('.js'))) assert.ok(!(await readFile(`dist/assets/${file}`,'utf8')).includes('supabase.co'),'O build não deve integrar com o Supabase')
  await page.getByRole('button',{name:'Concluir Escolher seu próximo passo',exact:true}).click()
  await context.setOffline(true)
  await page.reload()
  await page.getByRole('button',{name:'Desfazer Escolher seu próximo passo',exact:true}).waitFor()
  await page.goto('http://127.0.0.1:4173/jornada')
  await page.getByRole('heading',{name:'Sua jornada',exact:true}).waitFor()
  await mkdir('test-results',{recursive:true})
  await page.screenshot({path:'test-results/producao-offline.png',fullPage:true})
  assert.deepEqual(errors,[])
  console.log('PASS: entrada direta, manifest, cache público e rotina local disponível offline.')
} finally {await context.close();await browser.close()}
